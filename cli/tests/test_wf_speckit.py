def test_004_all_5_artifacts_pass():
    """5개 산출물(spec/plan/tasks/test-criteria + constitution) 모두 존재 → G1 PASS."""
    with tempfile.TemporaryDirectory() as tmp:
        root = _make_project(
            Path(tmp),
            spec="# Spec\n## FR-001\nLogin feature\n## FR-002\nLogout feature",
            plan="# Plan\n[FR-001] Implement login\n[FR-002] Implement logout",
            tasks="# Tasks\n- [ ] T01 [FR-001] Login\n- [ ] T02 [FR-002] Logout",
            test_criteria="# Test\n[FR-001] Login test\n[FR-002] Logout test",
            constitution="# Constitution\n- MUST follow REST conventions",
        )
        passed, evals = evaluate_plan_gate(root)
        assert passed, f"G1 should PASS: {evals}"
        # 4 existence + 0 NC + 1 task + 3 FR cross-ref + 1 constitution = 9
        assert len(evals) >= 8


