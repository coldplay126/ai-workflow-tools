"""Workflow spec-kit acceptance tests — WF-TEST-004.

Scope: G1 gate deterministic evaluation — artifact existence, FR-NNN
cross-reference coverage, constitution path resolution, [NEEDS CLARIFICATION]
markers. The G1 gate requires 4 core artifacts (spec/plan/tasks/test-criteria)
and optionally validates constitution via manifest. The 5th artifact
(constitution) is generated by the plan SKILL.md prompt, not enforced by
the gate; constitution gate-check only fires when manifest.constitution_path
is set.

Reference: docs/tests/workflow-and-multi-agent.md § WF-TEST-004
"""
